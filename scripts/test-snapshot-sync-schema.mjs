/** Real PostgreSQL helper checks in a NEW database; no application schema/data reads. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { root, migrationRoot, client, readServer, newDatabaseName, catalog, quoteSql, verifyManifest } from './lib/cloud-bootstrap.mjs';
import { ensureSnapshotSyncSchema, SNAPSHOT_SYNC_FAMILIES } from './lib/snapshot-sync-schema.mjs';

const started = Date.now();
verifyManifest();
const connection = client(readServer(), newDatabaseName('test_bootstrap'));
connection.create();
const databaseName = connection.databaseName;
console.log(`Created isolated snapshot-helper fixture: ${databaseName}`);
assert.equal(connection.checkedSql('SELECT current_database();'), databaseName);
const guard = `DO $$ BEGIN IF current_database() <> ${quoteSql(databaseName)} THEN RAISE EXCEPTION 'Wrong fixture'; END IF; END $$;`;
const mutate = sql => connection.checkedSql(`${guard}\nSET LOCAL search_path = public;\n${sql}`, { transaction: true });
mutate(`CREATE TABLE organizations (id TEXT PRIMARY KEY);
CREATE TABLE organization_users ("organizationId" TEXT NOT NULL, "userId" TEXT NOT NULL, PRIMARY KEY ("organizationId", "userId"));
CREATE TABLE master_categories (id TEXT PRIMARY KEY);`);
// Install the actual original category/master migrations, before organization CHECK expansion.
mutate(SNAPSHOT_SYNC_FAMILIES.map(family => fs.readFileSync(path.join(migrationRoot, family.migration, 'migration.sql'), 'utf8')).join('\n'));
mutate(`INSERT INTO organizations VALUES ('fixture-org');
INSERT INTO organization_users VALUES ('fixture-org','fixture-user');
INSERT INTO master_categories VALUES ('fixture-category');
INSERT INTO desktop_sync_devices (id,"organizationId","userId") VALUES ('fixture-device','fixture-org','fixture-user');
INSERT INTO desktop_sync_clocks VALUES ('fixture-org','category-epoch',7);
INSERT INTO desktop_sync_category_versions VALUES ('fixture-org','fixture-category',3);
INSERT INTO desktop_sync_changes ("organizationId",sequence,"categoryId","operationId",category) VALUES ('fixture-org',7,'fixture-category','category-operation','{"name":"Preserved category","version":3}');
INSERT INTO desktop_sync_receipts ("organizationId","deviceId","operationId","userId","requestHash",result) VALUES ('fixture-org','fixture-device','master-operation','fixture-user','original-request-hash','{"entityType":"uom","record":{"id":"unit","version":5}}');
INSERT INTO desktop_master_sync_clocks VALUES ('fixture-org','uom','uom-epoch',12), ('fixture-org','paymentTerm','term-epoch',4);
INSERT INTO desktop_master_sync_versions VALUES ('fixture-org','uom','unit',5), ('fixture-org','paymentTerm','term',2);
INSERT INTO desktop_master_sync_changes ("organizationId","entityType",sequence,"entityId","operationId",record) VALUES ('fixture-org','uom',12,'unit','master-operation','{"id":"unit","version":5,"name":"কেজি"}'), ('fixture-org','paymentTerm',4,'term','term-operation','{"id":"term","version":2,"days":30}');`);
const tables = ['organizations', 'organization_users', 'master_categories', ...SNAPSHOT_SYNC_FAMILIES.flatMap(family => family.tables)];
const rows = () => Object.fromEntries(tables.map(table => [table, JSON.parse(connection.checkedSql(`SELECT coalesce(jsonb_agg(t ORDER BY to_jsonb(t)::text), '[]'::jsonb) FROM "${table}" t;`))]));
const beforeRows = rows();
let ddlCalls = 0;
const observed = { ...connection, checkedSql(sql, options) { if (options?.transaction) ddlCalls++; return connection.checkedSql(sql, options); } };
const checks = [];
assert.deepEqual(ensureSnapshotSyncSchema(observed).applied, [SNAPSHOT_SYNC_FAMILIES[1].upgrade]);
assert.equal(ddlCalls, 1);
assert.deepEqual(rows(), beforeRows);
checks.push('Original populated master metadata receives only reviewed three-CHECK upgrade; all rows, clocks, versions, receipts and exact JSON unchanged');
ddlCalls = 0;
assert.deepEqual(ensureSnapshotSyncSchema(observed).applied, []);
assert.equal(ddlCalls, 0);
checks.push('Matching populated metadata repeats verification without DDL');
mutate('ALTER TABLE desktop_master_sync_changes RENAME TO helper_held_master_changes;');
const partial = catalog(connection);
assert.throws(() => ensureSnapshotSyncSchema(observed), /Partial snapshot sync schema/);
assert.equal(ddlCalls, 0);
assert.deepEqual(catalog(connection), partial);
mutate('ALTER TABLE helper_held_master_changes RENAME TO desktop_master_sync_changes;');
checks.push('Partial family fails before DDL and preserves catalog');
mutate('ALTER TABLE desktop_master_sync_clocks ALTER COLUMN sequence SET DEFAULT 9;');
const mismatch = catalog(connection);
assert.throws(() => ensureSnapshotSyncSchema(observed), /Mismatched snapshot sync schema/);
assert.equal(ddlCalls, 0);
assert.deepEqual(catalog(connection), mismatch);
mutate('ALTER TABLE desktop_master_sync_clocks ALTER COLUMN sequence SET DEFAULT 0;');
checks.push('Mismatched default fails before DDL and preserves catalog');
mutate('ALTER TABLE desktop_master_sync_clocks DROP CONSTRAINT desktop_master_sync_clocks_pkey; ALTER TABLE desktop_master_sync_clocks ADD CONSTRAINT desktop_master_sync_clocks_pkey PRIMARY KEY ("organizationId", "entityType") DEFERRABLE INITIALLY IMMEDIATE;');
const deferred = catalog(connection);
assert.throws(() => ensureSnapshotSyncSchema(observed), /index or primary-key state/);
assert.equal(ddlCalls, 0);
assert.deepEqual(catalog(connection), deferred);
mutate('ALTER TABLE desktop_master_sync_clocks DROP CONSTRAINT desktop_master_sync_clocks_pkey; ALTER TABLE desktop_master_sync_clocks ADD CONSTRAINT desktop_master_sync_clocks_pkey PRIMARY KEY ("organizationId", "entityType");');
checks.push('Actual deferrable primary key fails before DDL');
assert.throws(() => ensureSnapshotSyncSchema({ ...observed, databaseName: newDatabaseName('test_bootstrap') }), /wrong isolated database/);
assert.equal(ddlCalls, 0);
checks.push('Live database identity mismatch fails before DDL');
assert.deepEqual(ensureSnapshotSyncSchema(observed).applied, []);
assert.deepEqual(rows(), beforeRows);
verifyManifest();
const evidence = { databaseName, success: true, elapsedMs: Date.now() - started, checks, tableCount: tables.length, allExistingRowsPreserved: true, originalMigrationsUnchanged: true, sourceApplicationDbAccessed: false, sourceApplicationRowsCopied: false, fullSnapshotCliExercised: false, boundary: 'Helper against actual original migrations with minimal FK prerequisites and deliberately inserted metadata; no application dump or full migration deployment claimed.' };
fs.mkdirSync(path.join(root, '.temp'), { recursive: true });
fs.writeFileSync(path.join(root, '.temp', `${databaseName}-snapshot-upgrade-proof.json`), `${JSON.stringify(evidence, null, 2)}\n`, { flag: 'wx' });
console.log(JSON.stringify(evidence, null, 2));
